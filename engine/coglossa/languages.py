# Script subtags FLORES uses, and the common ones beyond it.
SCRIPT_NAMES: dict[str, str] = {
    "Arab": "Arabic script",
    "Beng": "Bengali script",
    "Cyrl": "Cyrillic script",
    "Deva": "Devanagari script",
    "Ethi": "Ethiopic script",
    "Grek": "Greek script",
    "Hans": "Simplified Chinese characters",
    "Hant": "Traditional Chinese characters",
    "Hebr": "Hebrew script",
    "Latn": "Latin script",
    "Olck": "Ol Chiki script",
    "Tfng": "Tifinagh script",
    "Tibt": "Tibetan script",
}


def label(tag: str) -> str:
    """'Hausa (ha)', 'Chinese, in Simplified Chinese characters (zh-Hans)', or the tag itself."""
    parts = tag.split("-")
    name = LANGUAGE_NAMES.get(parts[0].lower())
    if name is None:
        return tag
    script = next((SCRIPT_NAMES.get(p.title()) for p in parts[1:] if len(p) == 4), None)
    return f"{name}, in {script} ({tag})" if script else f"{name} ({tag})"
